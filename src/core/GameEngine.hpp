namespace draughts::core {

    enum class GameResult : unsigned char { Ongoing, RedWins, YellowWins, Draw };

    struct MoveRecord {
        Move   move;
        Color  mover;
        bool   movedKing;
        bool   wasCapture;
        bool   wasPromoted;  ///< piece became a King AS A RESULT of this move
        std::uint64_t positionHashAfter;
    };

    class GameEngine {
    public:
        GameEngine();
        explicit GameEngine(RuleSet rules);

        // ?????? Lifecycle ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
        void newGame(RuleSet rules = RuleSet::InternationalMaxCapture,
            Color    first = Color::Red);
        void setRules(RuleSet r) noexcept { state_.setRules(r); }

        // ?????? Queries ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
        [[nodiscard]] const Board& board()  const noexcept { return board_; }
        [[nodiscard]] const GameState& state()  const noexcept { return state_; }
        [[nodiscard]] RuleSet          rules()  const noexcept { return state_.rules(); }
        [[nodiscard]] Color            sideToMove() const noexcept { return state_.sideToMove(); }
        [[nodiscard]] int              ply()    const noexcept { return state_.ply(); }
        [[nodiscard]] GameResult       result() const noexcept { return result_; }

        [[nodiscard]] MoveSpan legalMoves() const noexcept {
            return generateLegalMoves(board_, state_.sideToMove(), state_.rules());
        }

        /// Combined position hash (pieces + side + rules).
        [[nodiscard]] std::uint64_t positionHash() const noexcept;

        // ?????? Mutation ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
        /// Attempt to apply a fully specified move. Returns false if illegal.
        bool tryApply(const Move& move) noexcept;

        /// Undo / Redo ??? pure index flips over `history_`.
        bool undo() noexcept;
        bool redo() noexcept;
        [[nodiscard]] bool canUndo() const noexcept { return cursor_ > 0; }
        [[nodiscard]] bool canRedo() const noexcept { return cursor_ < history_.size(); }

        /// Give up: current side to move resigns.
        void resign() noexcept;

        /// Offer/accept a draw: engine simply records Draw.
        void agreeDraw() noexcept;

        // ?????? History ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
        [[nodiscard]] const std::vector<MoveRecord>& history() const noexcept { return history_; }
        [[nodiscard]] std::size_t historyCursor() const noexcept { return cursor_; }

    private:
        Board     board_{};
        GameState state_{};
        GameResult result_{ GameResult::Ongoing };

        std::vector<MoveRecord> history_{};
        std::size_t cursor_{ 0 };   // number of applied records

        // FMJD small-endgame counters (kings-only 3v1, 2v1).
        int kings3v1Plies_{ 0 };
        int kings2v1Plies_{ 0 };
    int fourPiecePlies_{0};   ///< plies at exactly 4 pieces on board

        void resetInternal();
        void updateResultAfterMove();
        void updateSmallEndgameCounters(Color mover, bool movedKing, bool wasCapture) noexcept;
        void applyMoveToBoard(const Move& move, bool wasAlreadyKing) noexcept;
        void undoMoveFromBoard(const Move& move, bool wasAlreadyKing) noexcept;
    };

} // namespace draughts::core
